CREATE TABLE SOPORTEDBA.LOG_ENMASCARADO_DET
(
  DETAIL_ID       RAW(16)      DEFAULT SYS_GUID() NOT NULL,
  RUN_ID          RAW(16)                          NOT NULL,
  STAGE_NAME      VARCHAR2(80 BYTE)                NOT NULL,
  OWNER_NAME      VARCHAR2(128 BYTE),
  TABLE_NAME      VARCHAR2(128 BYTE),
  START_TS        TIMESTAMP(6),
  END_TS          TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  ELAPSED_SECONDS NUMBER,
  ROWS_PROCESSED  NUMBER,
  STATUS          VARCHAR2(20 BYTE) DEFAULT 'OK'   NOT NULL,
  ERR_CODE        NUMBER,
  ERR_MSG         VARCHAR2(4000 BYTE),
  NOTES           VARCHAR2(4000 BYTE)
)
TABLESPACE USERS
PCTFREE    10
INITRANS   1
MAXTRANS   255
STORAGE    (
            INITIAL          64K
            NEXT             1M
            MINEXTENTS       1
            MAXEXTENTS       UNLIMITED
            PCTINCREASE      0
            BUFFER_POOL      DEFAULT
           )
LOGGING
NOCOMPRESS
NOCACHE;

COMMENT ON TABLE SOPORTEDBA.LOG_ENMASCARADO_DET IS 'Detalle por etapa del proceso de enmascarado: carga STG, TMT, merges por tabla, tiempos y filas.';

COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO_DET.DETAIL_ID IS 'ID único del registro de detalle.';
COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO_DET.RUN_ID IS 'ID del run principal en LOG_ENMASCARADO.';
COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO_DET.STAGE_NAME IS 'Nombre de la etapa registrada: TMT_MERGE, STG_LOAD, MERGE_TABLE, etc.';
COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO_DET.OWNER_NAME IS 'Esquema fuente procesado.';
COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO_DET.TABLE_NAME IS 'Tabla asociada a la etapa, cuando aplica.';
COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO_DET.START_TS IS 'Timestamp de inicio de la etapa.';
COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO_DET.END_TS IS 'Timestamp de fin de la etapa.';
COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO_DET.ELAPSED_SECONDS IS 'Duración aproximada de la etapa en segundos.';
COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO_DET.ROWS_PROCESSED IS 'Filas insertadas, levantadas o actualizadas por la etapa.';
COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO_DET.STATUS IS 'Estado de la etapa: OK, ERROR, WARN, SKIP.';
COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO_DET.ERR_CODE IS 'Código Oracle si la etapa falló o emitió advertencia.';
COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO_DET.ERR_MSG IS 'Mensaje de error o advertencia de la etapa.';
COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO_DET.NOTES IS 'Notas libres de la etapa.';

