CREATE TABLE SOPORTEDBA.LOG_ENMASCARADO
(
  RUN_ID             RAW(16)                    DEFAULT SYS_GUID()            NOT NULL,
  START_TS           TIMESTAMP(6)               NOT NULL,
  END_TS             TIMESTAMP(6),
  OWNER_NAME         VARCHAR2(128 BYTE),
  TABLE_NAME         VARCHAR2(128 BYTE),
  OP_LABEL           VARCHAR2(50 BYTE),
  MERGED_COUNT       NUMBER,
  BACKFILLED_COUNT   NUMBER,
  MISSING_AFTER_TMT  NUMBER,
  SESSION_ID         NUMBER,
  MODULE             VARCHAR2(64 BYTE),
  ACTION             VARCHAR2(64 BYTE),
  ERR_CODE           NUMBER,
  ERR_MSG            VARCHAR2(4000 BYTE),
  ERR_STACK          CLOB,
  ERR_CALLSTACK      CLOB,
  NOTES              VARCHAR2(4000 BYTE)
)
LOB (ERR_CALLSTACK) STORE AS SECUREFILE (
  TABLESPACE  USERS
  ENABLE      STORAGE IN ROW
  CHUNK       8192
  RETENTION
  NOCACHE
  LOGGING
  STORAGE    (
              INITIAL          104K
              NEXT             1M
              MINEXTENTS       1
              MAXEXTENTS       UNLIMITED
              PCTINCREASE      0
              BUFFER_POOL      DEFAULT
             ))
LOB (ERR_STACK) STORE AS SECUREFILE (
  TABLESPACE  USERS
  ENABLE      STORAGE IN ROW
  CHUNK       8192
  RETENTION
  NOCACHE
  LOGGING
  STORAGE    (
              INITIAL          104K
              NEXT             1M
              MINEXTENTS       1
              MAXEXTENTS       UNLIMITED
              PCTINCREASE      0
              BUFFER_POOL      DEFAULT
             ))
TABLESPACE USERS
PCTFREE    10
INITRANS   1
MAXTRANS   255
STORAGE    (
            INITIAL          64K
            NEXT             1M
            MINEXTENTS       1
            MAXEXTENTS       UNLIMITED
            PCTINCREASE      0
            BUFFER_POOL      DEFAULT
           )
LOGGING 
NOCOMPRESS 
NOCACHE;

COMMENT ON TABLE SOPORTEDBA.LOG_ENMASCARADO IS 'Registro de ejecuciones del proceso de enmascarado (runs): tiempos, métricas, sesión y errores.';

COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO.RUN_ID IS 'ID único del run de enmascarado. Generado con SYS_GUID() al iniciar.';

COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO.START_TS IS 'Timestamp de inicio del run.';

COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO.END_TS IS 'Timestamp de fin del run (éxito o error).';

COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO.OWNER_NAME IS 'Esquema fuente (p_owner) sobre el que corre el run (ej. PROD_ENTIDAD700).';

COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO.TABLE_NAME IS 'Tabla fuente específica cuando el proceso es por tabla; NULL si es general.';

COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO.OP_LABEL IS 'Operación/mode del run: REFRESH (full) o INCREMENTAL.';

COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO.MERGED_COUNT IS 'Filas afectadas por la construcción/actualización de TMT o merges principales.';

COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO.BACKFILLED_COUNT IS 'Filas insertadas por el backfill post-TMT (faltantes).';

COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO.MISSING_AFTER_TMT IS 'Cantidad de claves faltantes luego del backfill (idealmente 0).';

COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO.SESSION_ID IS 'ID de sesión Oracle (USERENV(''SESSIONID'')).';

COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO.MODULE IS 'Módulo de aplicación (DBMS_APPLICATION_INFO.SET_MODULE / USERENV MODULE).';

COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO.ACTION IS 'Acción/etapa dentro del módulo (USERENV ACTION).';

COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO.ERR_CODE IS 'Código de error Oracle si el run falló (SQLCODE).';

COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO.ERR_MSG IS 'Mensaje corto del error (SQLERRM).';

COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO.ERR_STACK IS 'Backtrace del error con línea exacta (DBMS_UTILITY.FORMAT_ERROR_BACKTRACE).';

COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO.ERR_CALLSTACK IS 'Pila de llamadas (DBMS_UTILITY.FORMAT_CALL_STACK).';

COMMENT ON COLUMN SOPORTEDBA.LOG_ENMASCARADO.NOTES IS 'Notas libres del run: parámetros de ejecución, hints, etc.';


